/** Core domain types. All money is stored as integer kopecks. */

export const ACCOUNT_TYPES = ['cash', 'debit', 'savings', 'credit'] as const;
export type AccountType = (typeof ACCOUNT_TYPES)[number];

export const TRANSACTION_KINDS = [
  'expense',
  'income',
  'transfer',
  'credit_payment',
  'debt_payment',
  'refund',
  'adjustment',
] as const;
export type TransactionKind = (typeof TRANSACTION_KINDS)[number];

export const CATEGORY_KINDS = ['expense', 'income'] as const;
export type CategoryKind = (typeof CATEGORY_KINDS)[number];

export type ThemePreference = 'system' | 'light' | 'dark';

export type Account = {
  id: string;
  name: string;
  type: AccountType;
  /** Signed opening balance. Credit accounts store debt as a negative number. */
  openingBalanceMinor: number;
  openingBalanceAt: string;
  currency: 'RUB';
  /** Only for credit accounts: the bank limit, never part of own money. */
  creditLimitMinor?: number;
  statementDay?: number;
  paymentDueDay?: number;
  color?: string;
  sortOrder: number;
  archived: boolean;
  createdAt: string;
  updatedAt: string;
};

export type Category = {
  id: string;
  name: string;
  kind: CategoryKind;
  icon: string;
  color?: string;
  sortOrder: number;
  isSystem: boolean;
  createdAt: string;
  updatedAt: string;
};

export type Transaction = {
  id: string;
  kind: TransactionKind;
  /** Positive magnitude. Adjustments use a signed amount. */
  amountMinor: number;
  occurredAt: string;
  description: string;
  accountId?: string;
  fromAccountId?: string;
  toAccountId?: string;
  categoryId?: string;
  debtId?: string;
  /** Stable idempotency key generated by the UI for each submit. */
  clientRequestId: string;
  source: 'manual' | 'template' | 'demo' | 'import';
  createdAt: string;
  updatedAt: string;
  deletedAt?: string | null;
  rev: number;
};

export type LedgerEntry = {
  id: string;
  transactionId: string;
  accountId: string | null;
  categoryId: string | null;
  amountMinor: number;
};

export type DebtDirection = 'owed_to_me' | 'i_owe';
export type DebtStatus = 'open' | 'paid';

export type Debt = {
  id: string;
  direction: DebtDirection;
  counterparty: string;
  amountMinor: number;
  paidMinor: number;
  dueDate?: string | null;
  note?: string;
  status: DebtStatus;
  createdAt: string;
  updatedAt: string;
  deletedAt?: string | null;
};

export type Goal = {
  id: string;
  name: string;
  targetMinor: number;
  savedMinor: number;
  deadline?: string | null;
  note?: string;
  color?: string;
  createdAt: string;
  updatedAt: string;
  deletedAt?: string | null;
};

export type PlannedPayment = {
  id: string;
  name: string;
  amountMinor: number;
  dayOfMonth: number;
  accountId?: string;
  categoryId?: string;
  active: boolean;
  note?: string;
  createdAt: string;
  updatedAt: string;
  deletedAt?: string | null;
};

export type InflowConfidence = 'confirmed' | 'likely' | 'possible';

export type PlannedInflow = {
  id: string;
  name: string;
  amountMinor: number;
  expectedDate: string;
  confidence: InflowConfidence;
  createdAt: string;
  updatedAt: string;
  deletedAt?: string | null;
};

export type Budget = {
  /** YYYY-MM */
  month: string;
  amountMinor: number;
  updatedAt: string;
};

export type AppSettings = {
  id: 'app';
  onboardingComplete: boolean;
  currency: 'RUB';
  monthlyBudgetMinor: number;
  defaultAccountId?: string;
  lastCategoryId?: string;
  theme: ThemePreference;
  lastBackupAt?: string;
  lastBackupFormat?: number;
  createdAt: string;
  updatedAt: string;
};

export type AuditLog = {
  id: string;
  at: string;
  action: string;
  entity: string;
  entityId: string | null;
  before?: unknown;
  after?: unknown;
};

export type TransactionDraft = {
  kind: TransactionKind;
  amountMinor: number;
  occurredAt?: string;
  description?: string;
  accountId?: string;
  fromAccountId?: string;
  toAccountId?: string;
  categoryId?: string;
  debtId?: string;
  clientRequestId?: string;
  source?: Transaction['source'];
};

export type AccountBalance = {
  account: Account;
  balanceMinor: number;
};

export type AccountWithBalance = Account & { balanceMinor: number };
